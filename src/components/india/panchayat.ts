export function tokenize(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/[.,!?;:()"'/\\-]/g, ' ')
    .split(/\s+/)
    .filter(Boolean)
    .map((t) => TRANSLIT[t] ?? t)
    .map((t) => SPELLING[t] ?? t)
    .filter((t) => !STOPWORDS.has(t));
}

