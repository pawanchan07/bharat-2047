export interface TrainedModel {
  vocab: string[];
  /** log P(class) */
  logPrior: Record<IntentId, number>;
  /** log P(token | class), Laplace-smoothed */
  logLik: Record<IntentId, Record<string, number>>;
  /** log P(a token never seen for this class), the smoothing floor */
  logFloor: Record<IntentId, number>;
  docs: number;
  /** milliseconds the training actually took, measured on this device */
  trainMs: number;
}

const ALPHA = 1; // Laplace smoothing

/** Count, smooth, take logs. This is the whole of the training step. */
export function trainClassifier(corpus = CORPUS): TrainedModel {
  const t0 = performance.now();

  const docCount = {} as Record<IntentId, number>;
  const tokenCount = {} as Record<IntentId, Record<string, number>>;
  const tokenTotal = {} as Record<IntentId, number>;
  const vocabSet = new Set<string>();

  for (const id of INTENT_IDS) {
    docCount[id] = 0;
    tokenCount[id] = {};
    tokenTotal[id] = 0;
  }

  for (const row of corpus) {
    docCount[row.intent] += 1;
    for (const tok of tokenize(row.text)) {
      vocabSet.add(tok);
      tokenCount[row.intent][tok] = (tokenCount[row.intent][tok] || 0) + 1;
      tokenTotal[row.intent] += 1;
    }
  }

  const vocab = Array.from(vocabSet).sort();
  const V = vocab.length;

  const logPrior = {} as Record<IntentId, number>;
  const logLik = {} as Record<IntentId, Record<string, number>>;
  const logFloor = {} as Record<IntentId, number>;

  for (const id of INTENT_IDS) {
    logPrior[id] = Math.log(docCount[id] / corpus.length);
    const denom = tokenTotal[id] + ALPHA * V;
    logFloor[id] = Math.log(ALPHA / denom);
    logLik[id] = {};
    for (const tok of vocab) {
      logLik[id][tok] = Math.log(((tokenCount[id][tok] || 0) + ALPHA) / denom);
    }
  }

  return { vocab, logPrior, logLik, logFloor, docs: corpus.length, trainMs: performance.now() - t0 };
}

export interface Classification {
  intent: IntentId;
  confidence: number;
  /** every class, best first */
  ranked: { intent: IntentId; logScore: number; prob: number }[];
  tokens: string[];
  known: string[];
  /** words the model has never seen: the honest measure of being out of distribution */
  oov: string[];
  oovRate: number;
  /** the tokens that moved the decision, as log-odds against the runner-up */
  evidence: { token: string; logOdds: number }[];
  threshold: number;
}

export const AUTO_THRESHOLD = 0.62;

/**
 * Two calibration constants, and they were fitted rather than guessed.
 *
 * Raw Naive Bayes sums log-likelihoods over tokens, which saturates the softmax at
 * 1.000 on any sentence longer than a few words, a confidence of "100%" that means
 * nothing. Dividing by the token count over-corrects the other way and flattens
 * everything to ~20%. Normalising by sqrt(n) sits between the two, and the
 * temperature then sets how sharply the remaining gap is read.
 *
 * Both were swept against the corpus: these values put in-distribution complaints
 * around 80-93% and out-of-distribution input under 40%, i.e. on opposite sides of
 * the auto-route threshold, which is the only property that actually matters here.
 */
const LENGTH_EXPONENT = 0.5;
const TEMPERATURE = 0.6;

export function classify(model: TrainedModel, text: string): Classification {
  const tokens = tokenize(text);
  const vocab = new Set(model.vocab);
  const known = tokens.filter((t) => vocab.has(t));
  const oov = tokens.filter((t) => !vocab.has(t));
  const oovRate = tokens.length ? oov.length / tokens.length : 1;

  const norm = known.length ? Math.pow(known.length, LENGTH_EXPONENT) : 1;
  const scored = INTENT_IDS.map((id) => {
    let sum = 0;
    for (const t of known) sum += model.logLik[id][t] ?? model.logFloor[id];
    const logScore = (model.logPrior[id] + (known.length ? sum / norm : 0)) / TEMPERATURE;
    return { intent: id, logScore };
  });

  const max = Math.max(...scored.map((s) => s.logScore));
  const exps = scored.map((s) => Math.exp(s.logScore - max));
  const sumExp = exps.reduce((a, b) => a + b, 0);
  const ranked = scored
    .map((s, i) => ({ ...s, prob: exps[i] / sumExp }))
    .sort((a, b) => b.prob - a.prob);

  // Calibration. An unqualified 0.94 on a two-word sentence would be a lie, so the
  // raw softmax is discounted by out-of-vocabulary share and by how little evidence
  // there was to begin with.
  const evidencePenalty = known.length === 0 ? 0 : Math.min(1, known.length / 3);
  const confidence = ranked[0].prob * (1 - 0.5 * oovRate) * evidencePenalty;

  const top = ranked[0].intent;
  const runnerUp = ranked[1]?.intent ?? top;
  const evidence = Array.from(new Set(known))
    .map((token) => ({
      token,
      logOdds:
        (model.logLik[top][token] ?? model.logFloor[top]) -
        (model.logLik[runnerUp][token] ?? model.logFloor[runnerUp]),
    }))
    .sort((a, b) => b.logOdds - a.logOdds)
    .slice(0, 6);

  return {
    intent: top, confidence, ranked, tokens, known, oov, oovRate,
    evidence, threshold: AUTO_THRESHOLD,
  };
}

/* ---------------------------------------------------------------- evaluation */

export interface LooResult {
  correct: number;
  total: number;
  accuracy: number;
  ms: number;
  misses: { text: string; want: IntentId; got: IntentId; confidence: number }[];
  /** share of misses the confidence gate would have caught anyway */
  missesCaughtByGate: number;
}

/**
 * Leave-one-out cross-validation, run for real when you press the button.
 *
 * It retrains the model 120 times, each time holding one example out, and classifies
 * the held-out line. This is the only number in the demo that says how good the model
 * actually is, and the second number matters more than the first: of the lines it got
 * wrong, how many did the confidence gate refuse to auto-route anyway. A model that is
 * wrong and knows it is a different product from one that is wrong and confident.
 */
export function leaveOneOut(corpus = CORPUS): LooResult {
  const t0 = performance.now();
  let correct = 0;
  let caught = 0;
  const misses: LooResult['misses'] = [];

  for (let i = 0; i < corpus.length; i++) {
    const held = corpus[i];
    const m = trainClassifier(corpus.filter((_, j) => j !== i));
    const r = classify(m, held.text);
    if (r.intent === held.intent) {
      correct += 1;
    } else {
      if (r.confidence < AUTO_THRESHOLD) caught += 1;
      misses.push({ text: held.text, want: held.intent, got: r.intent, confidence: r.confidence });
    }
  }

  return {
    correct,
    total: corpus.length,
    accuracy: correct / corpus.length,
    ms: performance.now() - t0,
    misses,
    missesCaughtByGate: caught,
  };
}

