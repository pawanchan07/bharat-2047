const NUMBER_WORDS: Record<string, number> = {
  ek: 1, do: 2, teen: 3, char: 4, panch: 5, chhe: 6, che: 6, saat: 7, aath: 8,
  nau: 9, das: 10, one: 1, two: 2, three: 3, four: 4, five: 5, six: 6, seven: 7,
  eight: 8, nine: 9, ten: 10,
};

const UNIT_DAYS: Record<string, number> = { din: 1, hafta: 7, mahina: 30, saal: 365 };

const DOCUMENT_TERMS: Record<string, string> = {
  aadhaar: 'Aadhaar', aadhar: 'Aadhaar', adhaar: 'Aadhaar',
  ration: 'Ration card', khata: 'Bank account', passbook: 'Bank passbook',
  job: 'Job card', khatauni: 'Khatauni', khasra: 'Khasra', patta: 'Patta',
  ayushman: 'Ayushman card', voter: 'Voter ID', epic: 'Voter ID',
  praman: 'Certificate', muster: 'Muster roll',
};

const SCHEME_TERMS: Record<string, string> = {
  vridha: 'IGNOAPS (old-age pension)', buzurg: 'IGNOAPS (old-age pension)',
  vidhwa: 'IGNWPS (widow pension)', widow: 'IGNWPS (widow pension)',
  manrega: 'MGNREGA', awas: 'PMAY-Gramin', kisan: 'PM-KISAN',
  ayushman: 'Ayushman Bharat', jal: 'Jal Jeevan Mission',
};

export function extractEntities(text: string): Entities {
  const toks = text
    .toLowerCase()
    .replace(/[.,!?;:]/g, ' ')
    .split(/\s+/)
    .filter(Boolean)
    .map((t) => TRANSLIT[t] ?? t)
    .map((t) => SPELLING[t] ?? t);

  const list: Entity[] = [];
  let durationDays: number | undefined;
  let amount: number | undefined;
  const documents: string[] = [];
  const schemes: string[] = [];

  for (let i = 0; i < toks.length; i++) {
    const t = toks[i];

    // "3 mahina", "teen mahina", "10 din"
    const unit = UNIT_DAYS[t];
    if (unit && i > 0) {
      const prev = toks[i - 1];
      const n = /^\d+$/.test(prev) ? parseInt(prev, 10) : NUMBER_WORDS[prev];
      if (n) {
        const days = n * unit;
        if (durationDays === undefined || days > durationDays) durationDays = days;
        list.push({ kind: 'duration', label: 'How long', value: `${n} × ${t} = ${days} days` });
      }
    }

    // "rs 2000", "₹2,000", "paisa 2000"
    const money = t.match(/^(?:rs\.?|₹)?(\d[\d,]{2,})$/);
    if (money && (/^(?:rs|₹)/.test(t) || toks[i - 1] === 'paisa' || toks[i - 1] === 'rs')) {
      const v = parseInt(money[1].replace(/,/g, ''), 10);
      amount = v;
      list.push({ kind: 'amount', label: 'Amount', value: `₹${v.toLocaleString('en-IN')}` });
    }

    const doc = DOCUMENT_TERMS[t];
    if (doc && !documents.includes(doc)) {
      documents.push(doc);
      list.push({ kind: 'document', label: 'Document named', value: doc });
    }

    const sch = SCHEME_TERMS[t];
    if (sch && !schemes.includes(sch)) {
      schemes.push(sch);
      list.push({ kind: 'scheme', label: 'Scheme named', value: sch });
    }
  }

  return { list, durationDays, amount, documents, schemes };
}

